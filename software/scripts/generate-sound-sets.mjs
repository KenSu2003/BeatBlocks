// Existing drum samples + four original synthesized sounds; no downloaded audio.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const firmware=new URL('../../sound/reed_bridge/',import.meta.url);
const rate=44100;
function readDrum(id){
 const source=readFileSync(new URL(id+'_pcm.h',firmware),'utf8');
 return Int16Array.from(source.match(/PROGMEM = \{([\s\S]*?)\};/)[1].match(/-?\d+/g),Number);
}
function synth(id,duration){
 const out=new Float64Array(Math.ceil(rate*duration));let seed=17,previous=0,phase=0;
 for(let i=0;i<out.length;i++){
  const t=i/rate;seed=(Math.imul(seed,1664525)+1013904223)>>>0;
  const noise=seed/2147483648-1,high=noise-previous;previous=noise;
  let x=0;
  if(id==='tom'){
   phase+=2*Math.PI*(110+100*Math.exp(-t*28))/rate;
   x=Math.sin(phase)*Math.exp(-t*18)+.18*Math.sin(phase*1.57)*Math.exp(-t*30);
  }else if(id==='clap'){
   for(const start of [0,.012,.024])if(t>=start)x+=high*Math.exp(-(t-start)*95)*.35;
   if(t>=.036)x+=high*Math.exp(-(t-.036)*35)*.5;
  }else if(id==='woodblock'){
   x=(Math.sin(2*Math.PI*740*t)+.55*Math.sin(2*Math.PI*1120*t))*Math.exp(-t*55);
  }else if(id==='claves'){
   x=(Math.sin(2*Math.PI*2100*t)+.25*Math.sin(2*Math.PI*3250*t))*Math.exp(-t*95);
  }
  // Short attack and final fade avoid discontinuities at sample boundaries.
  out[i]=x*Math.min(1,t/.0015)*Math.min(1,(out.length-1-i)/(rate*.008));
 }
 const peak=out.reduce((m,x)=>Math.max(m,Math.abs(x)),.0001);
 return Int16Array.from(out,x=>Math.round(x/peak*.82*32767));
}
const samples={kick:readDrum('kick'),snare:readDrum('snare'),tom:synth('tom',.26),clap:synth('clap',.18),woodblock:synth('woodblock',.12),claves:synth('claves',.075)};
mkdirSync(new URL('generated/',firmware),{recursive:true});
for(const [id,pcm] of Object.entries(samples)){
 if(id==='kick'||id==='snare')continue;
 const name=id.toUpperCase();
 const lines=Array.from({length:Math.ceil(pcm.length/16)},(_,i)=>'  '+Array.from(pcm.slice(i*16,i*16+16)).join(', ')+',');
 writeFileSync(new URL(`generated/${id}_pcm.h`,firmware),`// Generated by software/scripts/generate-sound-sets.mjs\n#pragma once\n#include <Arduino.h>\nstatic const int ${name}_SAMPLE_RATE = ${rate};\nstatic const size_t ${name}_NUM_SAMPLES = ${pcm.length};\nstatic const int16_t ${name}_PCM[${pcm.length}] PROGMEM = {\n${lines.join('\n')}\n};\n`);
}
const packed={};
for(const [id,pcm] of Object.entries(samples)){
 const bytes=Buffer.alloc(pcm.length*2);pcm.forEach((v,i)=>bytes.writeInt16LE(v,i*2));packed[id]=bytes.toString('base64');
}
writeFileSync(new URL('../lib/sound-samples.mjs',import.meta.url),`// Generated PCM shared with ESP32; signed 16-bit little-endian, mono.\nexport const SOUND_SAMPLE_RATE=${rate};\nexport const SOUND_PCM=${JSON.stringify(packed,null,1)};\n`);
console.log(`Generated ${Object.keys(samples).length} instruments (${Object.values(samples).reduce((n,p)=>n+p.byteLength,0)} PCM bytes).`);
